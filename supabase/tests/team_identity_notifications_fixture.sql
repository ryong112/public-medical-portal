-- Disposable PostgreSQL/PGlite ONLY. This is not a production migration.
create role anon nologin;
create role authenticated nologin;
create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
grant usage on schema auth to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;

create schema storage;
create table storage.objects(id uuid primary key default gen_random_uuid(), bucket_id text);
create table public.messages(
  id bigint generated by default as identity primary key,
  content text not null, sender_id text, parent_id bigint, created_at timestamptz default now()
);
create table public.files(
  id bigint generated by default as identity primary key,
  name text, url text, size bigint, category text
);
create table public.categories(id bigint generated by default as identity primary key, name text);
create table public.schedules(
  id bigint generated by default as identity primary key,
  title text not null, date date not null, end_date date,
  start_time time, end_time time, is_completed boolean not null default false,
  recurrence_status text not null default 'active'
);
